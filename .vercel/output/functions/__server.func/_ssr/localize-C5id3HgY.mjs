function englishQueriesFor(query) {
	loadCache();
	const needle = cacheKey(query).toLowerCase();
	if (needle.length < 4) return [];
	const exact = [];
	const partial = [];
	for (const [original, entry] of memory) {
		const translated = entry.text.toLowerCase();
		if (translated === needle) exact.push(original);
		else if (needle.length >= 8 && translated.length >= 8 && (translated.includes(needle) || needle.includes(translated))) partial.push(original);
		if (exact.length >= 2) break;
	}
	return [...exact, ...partial].slice(0, 2);
}
function displayFromCache(values, lang) {
	loadCache();
	const out = {};
	for (const value of values) {
		const key = cacheKey(value);
		if (!wantsIndonesian(lang)) {
			let original = key;
			for (const [source, entry] of memory) if (entry.text.toLowerCase() === key.toLowerCase()) {
				original = source;
				break;
			}
			out[value] = original;
			continue;
		}
		out[value] = resolve(key).text;
	}
	return out;
}
